"""Prueba de humo del prototipo Nexo.

Uso:  python tests/smoke.py
Requiere: pip install playwright && playwright install chromium
"""
import asyncio
import pathlib
import sys

from playwright.async_api import async_playwright

URL = (pathlib.Path(__file__).resolve().parent.parent / "index.html").as_uri()


async def main() -> int:
    fails = []

    def check(cond, msg):
        print(("OK   " if cond else "FAIL ") + msg)
        if not cond:
            fails.append(msg)

    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=__import__("os").environ.get("CHROME_PATH") or None)
        pg = await b.new_page(viewport={"width": 1280, "height": 900})
        errs = []
        pg.on("pageerror", lambda e: errs.append(str(e)))

        # cuenta nueva
        await pg.goto(URL + "#registro")
        await pg.evaluate("localStorage.clear(); sessionStorage.clear()")
        await pg.reload()
        await pg.fill("#r-name", "Prueba Nexo")
        await pg.fill("#r-carnet", "20231234567")
        await pg.dispatch_event("#r-carnet", "input")
        await pg.fill("#r-mail", "prueba@correo.unimet.edu.ve")
        await pg.fill("#r-pass", "clave12345")
        await pg.click("#registerForm button[type=submit]")
        await pg.wait_for_timeout(800)
        check(await pg.evaluate("location.hash") == "#inicio", "registro lleva a inicio")

        # una cuenta nueva sin materias es enviada al formulario previo
        await pg.goto(URL + "#materias")
        await pg.wait_for_timeout(300)
        check(await pg.evaluate("location.hash") == "#inscripcion", "sin materias -> formulario de inscripción")

        await pg.select_option("#insCareer", "Derecho")
        await pg.click("[data-mcount='2']")
        rows = pg.locator("#insRows input")
        await rows.nth(0).fill("derecho constitucional")
        await rows.nth(1).fill("BPTEJ05")
        await pg.click("#insForm button[type=submit]")
        await pg.wait_for_timeout(300)
        lista = await pg.inner_text("#matList")
        check("BPTEJ11" in lista and "Obligaciones" in lista, "nombre y código se resuelven contra MATDB")
        await pg.goto(URL + "#materias")
        await pg.wait_for_timeout(300)
        cuotas = await pg.inner_text("#cuotasList")
        check("No aplica" not in cuotas and cuotas.count("Factura de") == 3, "una cuenta nueva ve las 3 facturas del trimestre")

        # comida: menús, carrito y pedido con tarjeta (cuenta nueva, carrito vacío)
        await pg.goto(URL + "#comida")
        await pg.wait_for_timeout(300)
        check(await pg.locator("#comida [data-open-local]").count() == 7, "comida muestra 7 locales y kioscos")
        await pg.fill("#c-search", "capuchino")
        check(await pg.locator("#comida [data-open-local]:visible").count() == 1, "la búsqueda encuentra productos dentro de los menús")
        await pg.click("[data-open-local='lapausa']")
        await pg.wait_for_timeout(300)
        check("La Pausa" in await pg.inner_text("#localHead"), "se abre el menú de La Pausa")
        await pg.click("[data-open-item='capuchino']")
        await pg.wait_for_timeout(300)
        await pg.click("[data-det-opt='0:1']")  # Grande +$0,50
        await pg.dispatch_event("[data-det-qty='1']", "click")  # botón solo con ícono
        check(await pg.inner_text("#detTotal") == "$6,60", "opciones y cantidad cambian el total")
        await pg.click("#detAdd")
        await pg.wait_for_timeout(300)
        check(await pg.evaluate("location.hash") == "#carrito" and "$6,60" in await pg.inner_text("#cartBody"), "el carrito refleja el producto")
        await pg.goto(URL + "#comida")
        await pg.fill("#c-search", "")
        await pg.click("[data-open-local='migrill']")
        await pg.wait_for_timeout(200)
        await pg.click("[data-open-item='clasica']")
        await pg.wait_for_timeout(200)
        check("Vaciar carrito" in await pg.inner_text("#detAdd"), "avisa al cambiar de local")
        await pg.click("#detAdd")
        await pg.wait_for_timeout(300)
        await pg.click("#cartPay")
        await pg.wait_for_timeout(300)
        pd = await pg.inner_text("#pdBody")
        check(await pg.evaluate("location.hash") == "#pedido" and "Mi Punto Grill" in pd and "En preparación" in pd, "pagar con tarjeta lleva al seguimiento del pedido")
        await pg.click("[data-sim-ready]")
        await pg.wait_for_timeout(300)
        check("Listo para retirar" in await pg.inner_text("#pdBody") and await pg.locator("#pdBody canvas").count() == 1, "el pedido listo muestra código y QR de retiro")
        await pg.click("[data-picked]")
        await pg.wait_for_timeout(200)
        check("Pedido retirado" in await pg.inner_text("#pdBody"), "el estudiante confirma que retiró el pedido")
        await pg.dispatch_event("#pdBody [data-go=factura]", "click")
        await pg.wait_for_timeout(300)
        fc = await pg.inner_text("#fcCard")
        check(await pg.evaluate("location.hash") == "#factura" and "Mi Punto Grill" in fc and "$6,50" in fc, "la factura del pedido está disponible")
        await pg.goto(URL + "#actividad")
        await pg.wait_for_timeout(200)
        check("Hamburguesa clásica" in await pg.inner_text("#actividad"), "el pedido aparece en Actividad")

        # cuenta demo
        await pg.evaluate("localStorage.removeItem('nexo-session'); sessionStorage.removeItem('nexo-session')")
        await pg.goto(URL + "#login")
        await pg.reload()
        await pg.fill("#l-mail", "ana.torres@correo.unimet.edu.ve")
        await pg.fill("#l-pass", "demo-nexo-01")
        await pg.click("#loginForm button[type=submit]")
        await pg.wait_for_timeout(800)
        await pg.goto(URL + "#materias")
        await pg.wait_for_timeout(300)
        check("BPTMI02" in await pg.inner_text("#matList"), "la cuenta demo conserva sus materias")

        # roles: estudiante crea ticket → admin asigna → moderadora reembolsa y resuelve → estudiante ve el resultado
        async def login(mail, pw):
            await pg.evaluate("localStorage.removeItem('nexo-session'); sessionStorage.removeItem('nexo-session')")
            await pg.goto(URL + "#login")
            await pg.reload()
            await pg.fill("#l-mail", mail)
            await pg.fill("#l-pass", pw)
            await pg.click("#loginForm button[type=submit]")
            await pg.wait_for_timeout(700)
        await pg.goto(URL + "#soporte")
        await pg.wait_for_timeout(300)
        await pg.click("#supNew")
        await pg.fill("#sp-subj", "Prueba de soporte")
        await pg.fill("#sp-msg", "Este es un ticket creado por la prueba de humo.")
        await pg.click("#supForm button[type=submit]")
        await pg.wait_for_timeout(300)
        nuevo = await pg.evaluate("JSON.parse(localStorage.getItem('nexo-tickets')).slice(-1)[0].id")
        check("Prueba de soporte" in await pg.inner_text("#supList"), "el estudiante crea una solicitud")
        await login("maria.vera@unimet.edu.ve", "demo-admin-01")
        check(await pg.evaluate("location.hash") == "#gestion", "la administradora entra a Tickets abiertos")
        check(nuevo in await pg.inner_text("#gsTable"), "la administradora ve el ticket nuevo")
        await pg.select_option(f"[data-assign='{nuevo}']", "lucia.rojas@unimet.edu.ve")
        await pg.goto(URL + "#materias")
        await pg.wait_for_timeout(200)
        check(await pg.evaluate("location.hash") == "#gestion", "la administración no entra a pantallas de estudiante")
        await login("lucia.rojas@unimet.edu.ve", "demo-mod-01")
        check(await pg.evaluate("location.hash") == "#moderacion", "la moderadora entra a Mis tickets")
        await pg.click(f"[data-md='{nuevo}']")
        await pg.fill("#mdText", "Respuesta de la moderadora.")
        await pg.click("#mdReply button[type=submit]")
        await pg.click("[data-md='TK-1048']")
        await pg.click("[data-md-act='refund']")
        await pg.click("[data-md-yes]")
        await pg.click("[data-md-resolve]")
        await pg.wait_for_timeout(200)
        await login("ana.torres@correo.unimet.edu.ve", "demo-nexo-01")
        await pg.goto(URL + "#soporte")
        await pg.wait_for_timeout(300)
        check("Respuesta de la moderadora." in await pg.inner_text("#supList"), "el estudiante ve la respuesta")
        await pg.goto(URL + "#actividad")
        await pg.wait_for_timeout(200)
        check("Reembolso · TK-1048" in await pg.inner_text("#actividad"), "el reembolso llega a la Actividad del estudiante")

        # creador: resumen, rol, respuesta y comisiones
        await login("diego.mendez@unimet.edu.ve", "demo-creador-01")
        check(await pg.evaluate("location.hash") == "#creador" and "$11.456" in await pg.inner_text("#crKpis"), "el creador ve el resumen con ingresos")
        await pg.goto(URL + "#creador-equipo")
        await pg.wait_for_timeout(300)
        await pg.check("#ceInvite input[value=admin]")
        await pg.fill("#ceInvite [name=email]", "pablo.mora@unimet.edu.ve")
        await pg.click("#ceInvite button[type=submit]")
        await pg.wait_for_timeout(200)
        check("Pablo Mora" in await pg.inner_text("#ceTeam"), "el creador invita a un administrador")
        await pg.dispatch_event("[data-ce='TK-1047']", "click")  # el aviso flotante puede tapar la fila
        await pg.fill("#ceText", "Respuesta del creador.")
        await pg.click("#ceReply button[type=submit]")
        await pg.wait_for_timeout(200)
        await pg.goto(URL + "#config")
        await pg.wait_for_timeout(200)
        await pg.fill("#cf-Comida", "7")
        await pg.click("#cfForm button[type=submit]")
        await pg.wait_for_timeout(200)
        await pg.goto(URL + "#movimientos")
        await pg.wait_for_timeout(200)
        await pg.click("#mvTabs [data-mv-tab='audit']")
        await pg.wait_for_timeout(200)
        audit = await pg.inner_text("#mvList")
        check("Invitó a pablo.mora@unimet.edu.ve como administrador" in audit and "Respondió en TK-1047" in audit and "Cambió comisiones" in audit, "el registro de cambios guarda las acciones del creador")

        # comercio: recibe el pedido de un estudiante, lo marca listo y lo entrega con el código
        await login("ana.torres@correo.unimet.edu.ve", "demo-nexo-01")
        await pg.goto(URL + "#carrito")
        await pg.wait_for_timeout(300)
        await pg.click("#cartPay")
        await pg.wait_for_timeout(300)
        codigo = await pg.evaluate("JSON.parse(localStorage.getItem('nexo-orders:ana.torres@correo.unimet.edu.ve')).slice(-1)[0].code")
        await login("pinchopan@comercio.nexo", "demo-local-01")
        check(await pg.evaluate("location.hash") == "#local-pedidos", "el comercio entra a su tablero de pedidos")
        clave = await pg.evaluate("[...document.querySelectorAll('[data-lp-ready]')].map(b => b.dataset.lpReady).find(k => k.startsWith('ana'))")
        check(bool(clave), "el comercio ve el pedido del estudiante")
        await pg.click(f"[data-lp-ready='{clave}']")
        await pg.wait_for_timeout(200)
        await pg.fill("#lpCodeForm input", codigo)
        await pg.dispatch_event("#lpCodeForm button[type=submit]", "click")
        await pg.wait_for_timeout(300)
        estado = await pg.evaluate("JSON.parse(localStorage.getItem('nexo-orders:ana.torres@correo.unimet.edu.ve')).slice(-1)[0]")
        check(bool(estado.get("readyMarked")) and bool(estado.get("pickedAt")), "el comercio marca listo y entrega con el código")
        await pg.goto(URL + "#local-menu")
        await pg.wait_for_timeout(200)
        await pg.click("[data-lm-item='almuerzo']")
        await pg.wait_for_timeout(200)
        await login("ana.torres@correo.unimet.edu.ve", "demo-nexo-01")
        await pg.goto(URL + "#comida")
        await pg.wait_for_timeout(200)
        await pg.dispatch_event("[data-open-local='pinchopan']", "click")
        await pg.wait_for_timeout(300)
        check("Agotado" in await pg.inner_text("#localMenu"), "el estudiante ve el producto agotado")

        # personal invitado: activa su cuenta sin carnet con el enlace de la invitación
        await login("maria.vera@unimet.edu.ve", "demo-admin-01")
        await pg.goto(URL + "#equipo")
        await pg.wait_for_timeout(300)
        await pg.fill("#equipo [data-invite] input", "andrea.soto@unimet.edu.ve")
        await pg.click("#equipo [data-invite] button[type=submit]")
        await pg.wait_for_timeout(200)
        token = await pg.evaluate("JSON.parse(localStorage.getItem('nexo-invites')).find(i => i.email === 'andrea.soto@unimet.edu.ve').token")
        await pg.evaluate("localStorage.removeItem('nexo-session'); sessionStorage.removeItem('nexo-session')")
        await pg.goto(URL + "#invitacion-" + token)
        await pg.reload()
        await pg.wait_for_timeout(300)
        await pg.fill("#iv-name", "Andrea Soto")
        await pg.fill("#iv-pass", "clave1234")
        await pg.fill("#iv-pass2", "clave1234")
        await pg.check("#iv-terms")
        await pg.click("#ivForm button[type=submit]")
        await pg.wait_for_timeout(800)
        check(await pg.evaluate("location.hash") == "#moderacion", "la persona invitada activa su cuenta sin carnet y entra como moderadora")

        check(not errs, f"sin errores de JavaScript {errs if errs else ''}")
        await b.close()

    print(f"\n{'Todo bien' if not fails else str(len(fails)) + ' fallo(s)'}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
